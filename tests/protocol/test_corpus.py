"""Corpus replay: the protocol layer verified against the synthetic corpus.

282 frame records in three generated files (`tests/corpus/`, written by
`tests.protocol.synthetic` from a fixed seed): a receive-only ambient mesh, group
text on two channels, and an exchange between sighop and a synthetic peer that
includes a room. What this proves and — just as importantly — what it does not, is
written down in `CORPUS.md`. In short: it proves framing, adverts, signature
verification and that the decoders agree with sighop's own encoders; it does not
prove interoperability with another MeshCore implementation, because the corpus is
generated by the code under test.
"""

