# Recorded expectations, typed in from a reviewed run of the generator's manifest
# (`uv run python -m tests.protocol.generate_corpus`) and asserted, never rewritten
# by tooling (design D10). A change to the generator changes the drift check, the
# manifest and these numbers together, in one reviewed change.
#
# Composition, over all 282 records — 264 received, 18 transmitted by sighop in
# the exchange file. Repeats are counted: 23 receptions repeat a packet already
# seen, all declared in the generator (`test_synthetic_corpus.py`).
EXPECTED_PAYLOAD_TYPES = {
    PayloadType.GRP_TXT: 59,
    PayloadType.TXT_MSG: 43,
    PayloadType.CONTROL: 25,
    PayloadType.ADVERT: 81,
    PayloadType.ACK: 24,
    PayloadType.ANON_REQ: 14,
    PayloadType.PATH: 14,
    PayloadType.RESPONSE: 7,
    PayloadType.REQ: 5,
    PayloadType.GRP_DATA: 4,
    PayloadType.TRACE: 6,
}
EXPECTED_ROUTE_TYPES = {
    RouteType.FLOOD: 188,
    RouteType.DIRECT: 93,
    RouteType.TRANSPORT_FLOOD: 1,
}
EXPECTED_HOP_COUNTS = {0: 83, 1: 73, 2: 57, 3: 43, 4: 19, 5: 7}
EXPECTED_HASH_SIZES = {1: 140, 2: 83, 3: 59}
EXPECTED_ADVERT_COUNT = 81
EXPECTED_ADVERT_FORMS = {0x92: 53, 0x81: 10, 0x91: 9, 0x93: 4, 0x83: 5}
"""By appdata flags: 0x92 repeater (located, named), 0x81 chat (named, no
location), 0x91 chat (located), 0x93 room server (located), 0x83 room server (no
location — the room sighop hosts)."""
EXPECTED_ADVERT_NAMES = 25
# The one transport-routed frame in the corpus: a TRANSPORT_FLOOD advert. Its codes
# are recorded here so a codec change that stops reading them fails on the corpus
# as well as on a hand-built fixture.
EXPECTED_TRANSPORT_FRAMES = 1
EXPECTED_TRANSPORT_CODES = (11329, 0)

# Every CONTROL frame the corpus holds is node discovery (decode-control-discovery),
# by (kind, payload length). The 14-byte key-prefix response is not generated and
# stays a hand-built fixture.
EXPECTED_CONTROL_FORMS = {
    ("discover_request", 6): 2,
    ("discover_request", 10): 3,
    ("discover_response", 38): 20,
}


@pytest.fixture(scope="module")
def frames() -> tuple[CorpusFrame, ...]:
    return load_corpus()


@pytest.fixture(scope="module")
def decoded(frames: tuple[CorpusFrame, ...]) -> list[tuple[CorpusFrame, Packet]]:
    out: list[tuple[CorpusFrame, Packet]] = []
    for frame in frames:
        packet = decode(frame.raw)
        assert isinstance(packet, Packet), f"frame failed to decode: {frame.describe()} -> {packet}"
        out.append((frame, packet))
    return out


# --- Replay ----------------------------------------------------------------


def test_corpus_holds_the_recorded_number_of_frames(
    frames: tuple[CorpusFrame, ...],
) -> None:
    assert len(frames) == EXPECTED_FRAME_COUNT


def test_every_corpus_frame_decodes(
    decoded: list[tuple[CorpusFrame, Packet]],
) -> None:
    assert len(decoded) == EXPECTED_FRAME_COUNT


def test_every_corpus_payload_parses(
    decoded: list[tuple[CorpusFrame, Packet]],
) -> None:
    for frame, packet in decoded:
        parsed = parse_payload(packet.payload_type, packet.payload)
        assert not isinstance(parsed, DecodeFailure), (
            f"payload failed to parse: {frame.describe()} -> {parsed}"
        )


def test_a_missing_corpus_file_fails_loudly(tmp_path: Path) -> None:
    """Never a silent pass on an empty corpus."""
    from tests.protocol import corpus

    with pytest.raises(CorpusError, match="missing"):
        original = corpus.CORPUS_DIR
        try:
            corpus.CORPUS_DIR = tmp_path
            corpus._load_file(CORPUS_FILES[0])
        finally:
            corpus.CORPUS_DIR = original


def test_corpus_files_are_treated_as_read_only(
    frames: tuple[CorpusFrame, ...],
) -> None:
    """The corpus files are generated artefacts that only the generator writes.
    Recording their digests here makes a stray write by the harness fail.
    """
    import hashlib

    for name in CORPUS_FILES:
        path = CORPUS_DIR / name
        assert path.is_file(), f"corpus file missing: {path}"
        before = hashlib.sha256(path.read_bytes()).hexdigest()
        load_corpus()
        after = hashlib.sha256(path.read_bytes()).hexdigest()
        assert before == after, f"the harness modified {name}"


def test_every_corpus_file_carries_synthetic_provenance(
    frames: tuple[CorpusFrame, ...],
) -> None:
    """A file with no `capture_meta` header is of unrecorded origin: neither
    generated nor evidence. Every corpus file is generated, and says so, with the
    generator version and seed that wrote it — and there is no sidecar.
    """
    import json

    for name in CORPUS_FILES:
        path = CORPUS_DIR / name
        with path.open("r", encoding="utf-8") as handle:
            first = json.loads(handle.readline())
        assert first.get("kind") == "capture_meta", f"{name} has no capture_meta header"
        assert first.get("synthetic") is True, f"{name} does not say it is synthetic"
        assert first["generator"]["version"] == GENERATOR_VERSION, name
        assert first["generator"]["seed"] == SEED, name
        assert not path.with_suffix(".meta.json").exists(), f"{name} has a sidecar"
    assert sorted(p.name for p in CORPUS_DIR.iterdir()) == sorted(CORPUS_FILES), (
        "the corpus directory holds a file the harness does not name"
    )


